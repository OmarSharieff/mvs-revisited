"""Build a report with saved scores, plots, and mesh images."""
from pathlib import Path
import json

from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    Image,
    PageBreak,
)
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib import colors


# Use paths from the project folder.
ROOT = Path(__file__).resolve().parents[1]
styles = getSampleStyleSheet()
story = []

def add_paragraph(text):
    """Add a paragraph and some space below it."""
    story.append(Paragraph(text, styles['BodyText']))
    story.append(Spacer(1, 8))


def add_heading(text):
    """Add a section title."""
    story.append(Paragraph(text, styles['Heading2']))


def add_page_number(canvas, document):
    """Put the page number at the bottom."""
    canvas.setFont('Helvetica', 9)
    canvas.drawRightString(555, 25, str(document.page))


# Read the scores saved by each run.
records = [
    json.loads(image_path.read_text())
    for image_path in sorted((ROOT / 'results').glob('*/metrics.json'))
]
add_heading('Multi-View Stereo Revisited')
add_paragraph('Implementation and experimental report | VUB Computer Vision 2026-27')
add_paragraph((
    'Authors: team names and student identifiers must be added before submission.'
    ' This implementation and draft report were generated with AI assistance. '
    'Individual student contributions have not been claimed or fabricated.'
))
add_paragraph((
    'Article: Michael Goesele, Brian Curless and Steven M. Seitz. Multi-View '
    'Stereo Revisited. CVPR 2006, volume 2, pages 2402-2409. DOI '
    '10.1109/CVPR.2006.199.'
))
add_heading('1 Summary')
add_paragraph((
    'We implement conservative multi-view stereo using RGB normalized '
    'cross-correlation, angular neighbor selection, threshold-based support, '
    'confidence estimation and coarse-to-fine depth search. Confidence-weighted '
    'projective fusion converts depth maps to a mesh. Controlled experiments use '
    'an analytically rendered textured cube and its exact depth maps. Parameter '
    'studies vary patch size and correlation threshold; a constant-color scene '
    'examines weak texture. A reduced-resolution TempleSparseRing experiment is '
    'included when its recorded outputs are available. Geometric depth error and '
    'coverage are reported jointly. This is a partial reproduction: projective '
    'fusion replaces the original VripPack range-mesh integration, image '
    'resolution is reduced, and the original benchmark ground truth is '
    'unavailable. The measurements below come from saved runs, not from the paper'
    ' or an assumed target.'
))
add_heading('2 Implementation and data')
add_paragraph((
    'Synthetic data are generated by code/synthetic.py. Twelve calibrated cameras'
    ' surround a 150 mm cube. Each ray intersects the axis-aligned cube and '
    'retains the first visible surface. RGB is evaluated from continuous '
    'sinusoidal functions of world position. Camera-z ground truth is passed only'
    ' to evaluation, not to stereo or fusion. This single procedural scene is a '
    'controlled diagnostic, not a representative benchmark of real reconstruction'
    ' performance.'
))
add_paragraph((
    'TempleSparseRing is obtained from the official Middlebury MVS dataset '
    'archive. Its README supplies the bounding box and cameras. The runner '
    'resizes the 640 by 480 images to 160 by 120 using bilinear resampling and '
    'transforms intrinsics with the corresponding half-pixel coordinate '
    'convention. No foreground masks, smoothing, hole filling or component '
    'cleanup are applied. Raw data acquisition is performed by code/download.py; '
    'links and checksum are recorded with the results.'
))
add_paragraph((
    'The stereo stage uses four angularly separated neighbors where available, '
    'with a minimum 4 degree separation from the reference and previously '
    'accepted neighbors. An RGB patch is centered at each reprojected candidate. '
    'Bilinear interpolation supplies fractional samples. Each channel is centered'
    ' independently; a single normalized dot product combines all channels. '
    'Near-zero-energy patches and out-of-bounds windows are invalid.'
))
add_paragraph((
    'At least two neighboring NCC scores must be strictly above the threshold. '
    'Their mean selects the depth; confidence sums their excess above threshold '
    'and divides by the total number of selected neighbors times one minus '
    'threshold. Camera-z candidates are bounded by the object box. A second '
    'search uses one tenth of the coarse step around the winning sample. '
    'Synthetic coarse spacing is 5 mm; real spacing is 2.5 mm. Missing depth '
    'remains invalid.'
))
add_heading('Fusion and differences from the article')
add_paragraph((
    'The fusion grid uses 4 mm voxels and a 16 mm surface band. Each voxel is '
    'projected into the depth maps, using nearest-pixel depth lookup. The '
    'measured camera-z minus voxel camera-z is normalized by the band width and '
    'accumulated with confidence weights. Marching cubes extracts zero crossings.'
    ' Faces unsupported by a fully observed voxel cell are rejected. This differs'
    ' from VripPack: no range-mesh scan conversion, grazing-angle weight, '
    'boundary weight or isolated-triangle rejection is reproduced. The coarse '
    "grid limits detail and should not be interpreted as matching the paper's "
    'submillimeter benchmark performance.'
))
add_heading('3 Quantitative results')
# Add one table row per run.
rows = [['Run', 'MAE mm', 'P90 mm', 'Coverage', 'Seconds', 'Faces']]
for record in records:
    # Show N/A for missing values and three decimals for the rest.
    format_metric = lambda key: 'N/A' if record.get(key) is None else f'{record[key]:.3f}'
    rows.append([
        record['run'],
        format_metric('mae_mm'),
        format_metric('p90_mm'),
        format_metric('foreground_coverage'),
        f"{record['seconds']:.1f}",
        str(record['faces']),
    ])
table = Table(rows, colWidths=[92, 65, 65, 65, 65, 70], repeatRows=1)
table.setStyle(TableStyle([
    ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#17365D')),
    ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
    ('GRID', (0, 0), (-1, -1), 0.4, colors.lightgrey),
    ('FONTSIZE', (0, 0), (-1, -1), 9),
    ('BOTTOMPADDING', (0, 0), (-1, -1), 7),
]))
story.append(table)
add_paragraph((
    'MAE and P90 measure absolute camera-z error on jointly valid foreground '
    'pixels. Coverage is the fraction of ground-truth foreground pixels with an '
    'estimated depth, not surface completeness. Timing includes stereo generation'
    ' only; fusion, plotting and report generation add time. Background '
    'predictions are counted separately in metrics.json. Real-image accuracy is '
    'N/A because the original ground truth is not distributed. These metrics '
    "cannot be directly compared with the paper's mesh-to-surface accuracy or "
    'completeness.'
))
add_heading('4 Qualitative results and discussion')
# Look up the scores by run name to compare them.
lookup = {record['run']: record for record in records}
if all((key in lookup for key in ['baseline', 'threshold04', 'threshold08', 'textureless'])):
    baseline = lookup['baseline']
    lower_threshold = lookup['threshold04']
    higher_threshold = lookup['threshold08']
    add_paragraph((
        'The baseline foreground depth MAE is '
        f"{baseline['mae_mm']:.2f}"
        ' mm at '
        f"{100 * baseline['foreground_coverage']:.1f}"
        '% coverage. Raising the NCC threshold to 0.8 reduces MAE to '
        f"{higher_threshold['mae_mm']:.2f}"
        ' mm but reduces coverage to '
        f"{100 * higher_threshold['foreground_coverage']:.1f}"
        '%. Lowering it to 0.4 increases coverage to '
        f"{100 * lower_threshold['foreground_coverage']:.1f}"
        '% while increasing MAE to '
        f"{lower_threshold['mae_mm']:.2f}"
        ' mm. This experiment supports the expected accuracy-coverage tradeoff on'
        ' this scene. It does not establish the same effect on all objects.'
    ))
    add_paragraph((
        'The baseline also predicts '
        f"{baseline['background_predictions']}"
        ' pixels outside the true foreground across all views. Boundary-related '
        'false matches remain a material failure. The textureless run has '
        f"{lookup['textureless']['mae_mm']:.2f}"
        ' mm MAE on the subset it predicts; its output should not be interpreted '
        'as successful reconstruction of an untextured object.'
    ))
# Add the saved plots and mesh images.
for name in ['baseline', 'window9', 'textureless', 'real']:
    image_path = ROOT / 'results' / name / 'diagnostics.png'
    if image_path.exists():
        story.append(Image(str(image_path), width=475, height=119))
        add_paragraph(name + (
            ': input, estimated depth, confidence and accepted correlation. '
            'Invalid depth pixels are blank. Depth scales are automatic; use '
            'numerical metrics for quantitative comparison.'
        ))
add_paragraph((
    'Large patches can improve support while blending boundaries; smaller patches'
    ' can preserve local detail but produce ambiguous correlations. Threshold '
    'changes affect both accepted coverage and error. High confidence is not a '
    'calibrated probability. The textureless scene may retain silhouette-based '
    'false matches even when most constant patches are rejected. Reported error '
    'must always be read alongside foreground coverage and background '
    'predictions.'
))
for name in ['baseline', 'real']:
    image_path = ROOT / 'results' / name / 'mesh.png'
    if image_path.exists():
        story.append(Image(str(image_path), width=260, height=260))
        add_paragraph(name + (
            ' reconstructed mesh. Views and axes are for inspection; no '
            'ground-truth alignment or rescaling was fitted.'
        ))
add_paragraph((
    'Limitations: only one synthetic geometry and one reduced-resolution real '
    'subset are tested. Sparse viewpoints, repeated procedural texture, fixed '
    'square image patches and coarse fusion can create missing or incorrect '
    'surfaces. The study does not reproduce all original datasets, reflection '
    'experiments or original volumetric weighting. No claim of official benchmark'
    ' equivalence is made. TA agreement is still needed for this scope and '
    'evaluation substitution.'
))
add_heading('5 Reproducibility checklist')
add_paragraph((
    'Code and tests are included. Install the pinned requirements in a virtual '
    'environment, then run bash run.sh. Seeds are fixed to zero; the procedural '
    'renderer is deterministic. run.sh regenerates the experiments and this '
    'report. Hardware, Python and platform are recorded in '
    'results/environment.json. Expected measurements are in the saved metrics '
    'files. Run python -m pytest tests -q to check geometry, NCC, voting, '
    'interpolation and fusion. Floating-point and runtime variation across '
    'platforms is expected.'
))
add_heading('References')
add_paragraph((
    'Goesele et al., CVPR 2006, supplied paper.pdf. Curless and Levoy, A '
    'Volumetric Method for Building Complex Models from Range Images, SIGGRAPH '
    '1996. Official dataset and evaluation information: '
    'https://vision.middlebury.edu/mview/ and '
    'https://vision.middlebury.edu/mview/data/ (checked 3 November 2026). The '
    'benchmark states that ground truth is not distributed and submissions are '
    'closed.'
))
# Save report.pdf in the project folder.
SimpleDocTemplate(
    str(ROOT / 'report.pdf'),
    rightMargin=50,
    leftMargin=50,
    topMargin=45,
    bottomMargin=45,
).build(
    story,
    onFirstPage=add_page_number,
    onLaterPages=add_page_number,
)
